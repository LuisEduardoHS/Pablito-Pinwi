"""Build the rigid part rig of the existing, disconnected Pablito mesh.

No art is replaced. Run after changing Models/pablitopinwi_textured.txt.
Uses Python's standard library; --check verifies the checked-in generated data.
"""
from pathlib import Path
from collections import defaultdict
import hashlib
import sys

PROJECT = Path(__file__).resolve().parents[1]
SOURCE = PROJECT / 'Models/pablitopinwi_textured.txt'
OUTPUT = PROJECT / 'Gameplay/PablitoRigData.h'


def generate():
    raw = SOURCE.read_bytes()
    text = raw.decode('utf-8').split('Data:', 1)[1]
    vertices = [tuple(map(float, line.split()[:3])) for line in text.splitlines() if line.strip()]
    assert len(vertices) % 3 == 0
    unique, indices, parents = {}, [], []
    for position in vertices:
        key = tuple(round(v, 5) for v in position)
        if key not in unique:
            unique[key] = len(parents)
            parents.append(len(parents))
        indices.append(unique[key])

    def root(i):
        while parents[i] != i:
            parents[i] = parents[parents[i]]
            i = parents[i]
        return i

    for i in range(0, len(indices), 3):
        a, b, c = indices[i:i+3]
        parents[root(b)] = root(a)
        parents[root(c)] = root(a)
    groups = defaultdict(list)
    for i, index in enumerate(indices):
        groups[root(index)].append(i)
    minimum = min(p[1] for p in vertices)
    bones = [None] * len(vertices)
    counts = [0] * 9
    for group in groups.values():
        points = [vertices[i] for i in group]
        x, y, z = (sum(p[axis] for p in points)/len(points) for axis in range(3))
        high_y = max(p[1] for p in points)-minimum
        if y-minimum < .65:
            bone = 4 if z < 0 else 5  # feet and their upper pads
        elif abs(z) > .85 and high_y < 2:
            bone = 2 if z < 0 else 3  # flippers
        elif high_y < 2 and abs(z) < .2 and x < .3:
            bone = 0  # inner and outer body
        elif x > .45 and abs(z) > .5:
            bone = 6 if z < 0 else 7  # eye whites and pupils
        elif x > .55 and y-minimum < 2.16 and abs(z) < .1:
            bone = 8  # lower beak, mouth interior and tongue
        else:
            bone = 1  # head, upper beak and head feathers
        counts[bone] += len(group)
        for i in group:
            bones[i] = bone
    assert all(counts), counts
    triangle_bones = []
    for i in range(0, len(vertices), 3):
        assert len(set(bones[i:i+3])) == 1
        triangle_bones.append(bones[i])
    lines = [
        '// Generated by Tools/rig_pablito.py. Do not edit by hand.',
        '// Source SHA-256: '+hashlib.sha256(raw).hexdigest(),
        '#ifndef GC_PABLITO_RIG_DATA_H', '#define GC_PABLITO_RIG_DATA_H',
        'namespace PablitoRigData {',
        f'constexpr unsigned VertexCount={len(vertices)}, BoneCount=9;',
        '// Body, Head, LeftWing, RightWing, LeftFoot, RightFoot, LeftEye, RightEye, Beak.',
        'const unsigned char TriangleBones[]={',
    ]
    lines += ['    '+','.join(map(str, triangle_bones[i:i+64]))+',' for i in range(0, len(triangle_bones), 64)]
    lines += ['};', '}', '#endif', '']
    return '\n'.join(lines), counts


if __name__ == '__main__':
    result, counts = generate()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='utf-8') == result, 'Regenerate the rig after changing the mesh.'
    else:
        OUTPUT.write_text(result, encoding='utf-8', newline='\n')
    print('PASS: intact rigid components, 9 bones, triangle assignments:', counts)
