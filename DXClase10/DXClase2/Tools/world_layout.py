"""Shared authored layout. Regenerate WorldLayout.h through generate_valley.py."""
import json
from pathlib import Path
import numpy as np

PROJECT = Path(__file__).resolve().parent.parent
DATA = json.loads((PROJECT/'WorldLayout.json').read_text(encoding='utf-8'))
EXTENT = float(DATA['extent'])

def river_x(z):
    r = DATA['river']
    return r['x_base'] + r['sine_amplitude']*np.sin(z/EXTENT*2*np.pi+r['sine_phase']) + z*r['x_drift_per_z']

def river_half_width(z):
    r = DATA['river']
    return r['half_width'] + r['width_variation']*np.sin(np.clip(z/EXTENT,0,1)*np.pi)

def river_height(z):
    levels = np.array(DATA['river']['levels'])
    return np.interp(z,levels[:,0],levels[:,1])

def bridge_coordinates(x,z):
    b=DATA['bridge'];a=np.deg2rad(b['yaw_degrees'])
    dx,dz=x-b['center'][0],z-b['center'][2]
    return dx*np.sin(a)+dz*np.cos(a),dx*np.cos(a)-dz*np.sin(a)

def bridge_controls():
    """Keep the road straight across the deck and turn beyond its railings."""
    b=DATA['bridge'];a=np.deg2rad(b['yaw_degrees']);inner=b['length']/2+8;outer=inner+19
    stations=[-outer,-inner,0,inner,outer]
    points=[(b['center'][0]+np.sin(a)*s,b['center'][2]+np.cos(a)*s) for s in stations]
    levels=[b['center'][1]+b['slope']*s for s in stations]
    return points,levels

